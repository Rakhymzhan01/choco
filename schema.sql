-- Choco database schema (PostgreSQL). Safe to run more than once.

-- Lookup tables: the same lists as CATEGORIES and DISTRICTS in js/data.js. Every deal points to one of each.
CREATE TABLE IF NOT EXISTS categories (
    id         text PRIMARY KEY,
    name       text NOT NULL,
    icon       text NOT NULL,
    sort_order smallint NOT NULL
);

CREATE TABLE IF NOT EXISTS districts (
    name       text PRIMARY KEY,
    sort_order smallint NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    text NOT NULL,
    last_name     text NOT NULL,
    email         text NOT NULL,
    password_hash text NOT NULL,
    role          text NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    phone         text NOT NULL DEFAULT '',
    dob           date,
    photo         text NOT NULL DEFAULT '',          -- small JPEG as a data URL
    created_at    timestamptz NOT NULL DEFAULT now()
);
-- one account per email, ignoring upper/lower case
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_key ON users (lower(email));

CREATE TABLE IF NOT EXISTS deals (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       text NOT NULL,
    merchant    text NOT NULL,
    category_id text NOT NULL REFERENCES categories (id),
    district    text NOT NULL REFERENCES districts (name),
    old_price   integer NOT NULL CHECK (old_price > 0),
    price       integer NOT NULL CHECK (price > 0),
    rating      numeric(2, 1) NOT NULL DEFAULT 4.5,
    reviews     integer NOT NULL DEFAULT 0,
    bought      integer NOT NULL DEFAULT 0,
    image       text NOT NULL,
    valid_until date NOT NULL,
    description text NOT NULL,
    features    text[] NOT NULL DEFAULT '{}',
    conditions  text NOT NULL,
    CHECK (price < old_price)
);
CREATE INDEX IF NOT EXISTS deals_category_idx ON deals (category_id);

-- a user's cart; deleting a user or a deal removes the matching rows
CREATE TABLE IF NOT EXISTS cart_items (
    user_id  bigint   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    deal_id  bigint   NOT NULL REFERENCES deals (id) ON DELETE CASCADE,
    position smallint NOT NULL,                      -- order in which items were added
    qty      smallint NOT NULL CHECK (qty BETWEEN 1 AND 10),
    PRIMARY KEY (user_id, deal_id)
);

-- booking numbers start at 10236 (10234 and 10235 are the demo bookings)
CREATE TABLE IF NOT EXISTS orders (
    id         bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 10236) PRIMARY KEY,
    user_id    bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status     text NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Confirmed', 'Completed', 'Cancelled')),
    usage_date date NOT NULL,
    usage_time time NOT NULL,
    people     smallint NOT NULL CHECK (people BETWEEN 1 AND 10),
    phone      text NOT NULL,
    comment    text NOT NULL DEFAULT '',
    payment    text NOT NULL,
    total      integer NOT NULL CHECK (total >= 0),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS orders_user_idx ON orders (user_id);

-- title / merchant / price are copied from the deal at purchase time,
-- so an old booking keeps its price even if the deal is edited or deleted
CREATE TABLE IF NOT EXISTS order_items (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    deal_id  bigint REFERENCES deals (id) ON DELETE SET NULL,
    title    text NOT NULL,
    merchant text NOT NULL,
    price    integer NOT NULL,
    qty      smallint NOT NULL CHECK (qty BETWEEN 1 AND 10),
    codes    text[] NOT NULL                         -- one coupon code per unit
);
CREATE INDEX IF NOT EXISTS order_items_order_idx ON order_items (order_id);

CREATE TABLE IF NOT EXISTS messages (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL,
    email      text NOT NULL,
    subject    text NOT NULL,
    message    text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

